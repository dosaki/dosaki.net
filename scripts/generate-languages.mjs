import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const seedPath = resolve(here, '../src/content/languages.seed.json')
const outPath = resolve(here, '../src/content/languages.generated.ts')

const USER = 'dosaki'
const CURRENT_YEAR = new Date().getFullYear()

/** GitHub reports Vue separately; the site counts it as JavaScript. */
const ALIASES = { vue: 'javascript' }

function loadSeed() {
  const seed = JSON.parse(readFileSync(seedPath, 'utf8'))
  for (const stat of Object.values(seed)) {
    if (stat.startYear !== null && stat.endYear === null) {
      stat.endYear = CURRENT_YEAR
    }
  }
  return seed
}

async function fetchJson(url) {
  const res = await fetch(url, {
    headers: { Accept: 'application/vnd.github+json', 'User-Agent': 'dosaki.net-build' },
  })
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`)
  return res.json()
}

async function augment(languages) {
  const repos = await fetchJson(`https://api.github.com/users/${USER}/repos?per_page=100`)
  const owned = repos.filter((repo) => !repo.fork)

  for (const repo of owned) {
    const names = Object.keys(await fetchJson(repo.languages_url))
    const year = new Date(repo.created_at).getFullYear()

    for (const raw of names) {
      const key = ALIASES[raw.toLowerCase()] ?? raw.toLowerCase()
      const stat = languages[key]
      if (!stat) continue

      if (!stat.projects.includes(repo.name)) stat.projects.push(repo.name)
      stat.startYear = Math.min(year, stat.startYear ?? 9999)
      stat.endYear = Math.max(year, stat.endYear ?? 0)
    }
  }
  return owned.length
}

const languages = loadSeed()

try {
  const count = await augment(languages)
  console.log(`generate-languages: merged ${count} GitHub repositories`)
} catch (error) {
  console.warn(`generate-languages: falling back to seed only — ${error.message}`)
}

writeFileSync(
  outPath,
  `// GENERATED by scripts/generate-languages.mjs — do not edit by hand.\n` +
    `// Regenerate with: npm run generate:languages\n\n` +
    `import type { LanguageMap } from './types'\n\n` +
    `export const languages: LanguageMap = ${JSON.stringify(languages, null, 2)}\n`,
)
console.log(`generate-languages: wrote ${outPath}`)
